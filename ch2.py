# ЗАДАЧА 2. Сколько дней ждать потепления
# ==================================================

# Дан массив temperatures, где temperatures[i] — температура в день i
# (дни нумеруются с 0).

# Верните массив answer той же длины, где answer[i] — количество дней,
# которое нужно подождать после дня i, чтобы температура стала строго выше.

# Если более тёплого дня впереди нет, answer[i] = 0.

# Пример 1:
# Вход:  [73, 74, 75, 71, 69, 72, 76, 73]
# Выход: [ 1,  1,  4,  2,  1,  1,  0,  0]

# Пояснение:
# В день 2 температура 75. Впервые теплее станет в день 6 (76),
# значит ждать 6 - 2 = 4 дня.

# Пример 2:
# Вход:  [30, 40, 50, 60]
# Выход: [ 1,  1,  1,  0]

# Пример 3:
# Вход:  [30, 30, 31]
# Выход: [ 2,  1,  0]

# Пояснение:
# Такая же температура не считается потеплением, нужна строго большая.


def daily_temperatures(temperatures):
    n = len(temperatures)
    answer = [0] * n
    stack = []

    for i, temp in enumerate(temperatures):
        while stack and temp > temperatures[stack[-1]]:
            prev_day = stack.pop()
            answer[prev_day] = i - prev_day

        stack.append(i)

    return answer

if __name__ == "__main__":
    assert daily_temperatures([73, 74, 75, 71, 69, 72, 76, 73]) == [1, 1, 4, 2, 1, 1, 0, 0]
    assert daily_temperatures([30, 40, 50, 60]) == [1, 1, 1, 0]
    assert daily_temperatures([30, 30, 31]) == [2, 1, 0]
    print("OK")