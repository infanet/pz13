# Дан массив целых чисел nums.

# Верните массив answer той же длины, в котором answer[i] равен
# произведению всех элементов nums, кроме nums[i].

# Ограничение: операцию деления использовать нельзя.

# Пример 1:
# Вход:  [1, 2, 3, 4]
# Выход: [24, 12, 8, 6]

# Пояснение:
# answer[0] = 2 · 3 · 4 = 24
# answer[1] = 1 · 3 · 4 = 12
# answer[2] = 1 · 2 · 4 = 8
# answer[3] = 1 · 2 · 3 = 6

# Пример 2:
# Вход:  [-1, 1, 0, -3, 3]
# Выход: [0, 0, 9, 0, 0]

# Пояснение:
# В массиве есть ноль, поэтому во всех позициях, кроме позиции самого нуля,
# произведение равно 0.
# answer[2] = -1 · 1 · (-3) · 3 = 9


def product_except_self(nums):
    n = len(nums)
    answer = [1] * n

    left = 1
    for i in range(n):
        answer[i] = left
        left *= nums[i]

    right = 1
    for i in range(n - 1, -1, -1):
        answer[i] *= right
        right *= nums[i]

    return answer
if __name__ == "__main__":
    assert product_except_self([1, 2, 3, 4]) == [24, 12, 8, 6]
    assert product_except_self([-1, 1, 0, -3, 3]) == [0, 0, 9, 0, 0]
    print("OK")